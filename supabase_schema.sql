create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 40),
  score integer not null check (score >= 0),
  total integer not null check (total = 3),
  answers jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.quiz_attempts enable row level security;
alter table public.quiz_admins enable row level security;

revoke all on public.quiz_attempts from anon, authenticated;
grant insert on public.quiz_attempts to anon, authenticated;
grant select on public.quiz_attempts to authenticated;
grant usage, select on sequence public.quiz_attempts_id_seq to anon, authenticated;

create policy "Anyone can submit a quiz attempt"
on public.quiz_attempts for insert to anon, authenticated
with check (score >= 0 and score <= total and total = 3);

create policy "Admins can read quiz attempts"
on public.quiz_attempts for select to authenticated
using (exists (
  select 1 from public.quiz_admins
  where quiz_admins.user_id = auth.uid()
));

create policy "Admins can read their own admin record"
on public.quiz_admins for select to authenticated
using (user_id = auth.uid());
